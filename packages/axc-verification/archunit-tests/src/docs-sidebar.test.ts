import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Docusaurus reports a dangling sidebar id only on a fresh site build, and a cached build hides it; an unlisted page
// builds fine but is unreachable. This mirrors the doc-id rules (path under docs/, extension dropped, numeric `NN-`
// prefixes dropped per segment, frontmatter `id` wins) so both fail here, naming the file to fix.
const docsApp = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../../apps/docs');

const NON_ID_KEYS = new Set(['type', 'label', 'href', 'dirName', 'className', 'description', 'title', 'slug', 'customProps']);
const NON_ID_VALUES = new Set(['doc', 'category', 'link', 'autogenerated', 'ref', 'html', 'generated-index']);

function docId(relativePath: string, content: string): string {
	const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(content)?.[1] ?? '';
	const explicit = /^id:\s*['"]?([^'"\r\n]+?)['"]?\s*$/m.exec(frontmatter)?.[1];
	const segments = relativePath
		.replace(/\.mdx?$/, '')
		.split('/')
		.map((segment) => segment.replace(/^\d+-/, ''));
	if (explicit) segments[segments.length - 1] = explicit;
	return segments.join('/');
}

function sidebarIds(source: string): { ids: Set<string>; autogenerated: boolean } {
	const body = source.replace(/^\s*(?:import|type)\b.*$/gm, '').replace(/\/\/.*$/gm, '');
	const ids = new Set<string>();
	for (const match of body.matchAll(/(?:(\w+)\s*:\s*)?['"`]([^'"`\r\n]+)['"`]/g)) {
		const [, key, value = ''] = match;
		if ((key && NON_ID_KEYS.has(key)) || NON_ID_VALUES.has(value) || value.startsWith('@') || !/^[\w./-]+$/.test(value)) continue;
		ids.add(value);
	}
	return { ids, autogenerated: /type\s*:\s*['"]autogenerated['"]/.test(body) };
}

function sidebarProblems(sidebarSource: string, docs: { relativePath: string; content: string }[]): string[] {
	const existing = new Map(docs.map((doc) => [docId(doc.relativePath, doc.content), doc.relativePath]));
	const { ids, autogenerated } = sidebarIds(sidebarSource);
	const dangling = [...ids].filter((id) => !existing.has(id)).map((id) => `apps/docs/sidebars.ts lists "${id}" but no page in apps/docs/docs/ has that id`);
	const unlisted = autogenerated ? [] : [...existing].filter(([id]) => !ids.has(id)).map(([id, file]) => `apps/docs/docs/${file} (id "${id}") is missing from apps/docs/sidebars.ts`);
	return [...dangling, ...unlisted];
}

async function docPages(dir: string, prefix = ''): Promise<{ relativePath: string; content: string }[]> {
	const entries = await readdir(dir, { withFileTypes: true });
	const pages = await Promise.all(
		entries.map(async (entry) => {
			const relativePath = `${prefix}${entry.name}`;
			if (entry.isDirectory()) return docPages(path.join(dir, entry.name), `${relativePath}/`);
			return /\.mdx?$/.test(entry.name) ? [{ relativePath, content: await readFile(path.join(dir, entry.name), 'utf8') }] : [];
		}),
	);
	return pages.flat();
}

describe('docs sidebar', () => {
	it('lists every docs page and only existing pages', async () => {
		const sidebar = await readFile(path.join(docsApp, 'sidebars.ts'), 'utf8');
		expect(sidebarProblems(sidebar, await docPages(path.join(docsApp, 'docs')))).toStrictEqual([]);
	});

	it('self-test: flags a dangling id and an unlisted page; honours numeric prefixes, frontmatter ids and autogenerated sidebars', () => {
		const docs = [
			{ relativePath: 'intro.md', content: '# Intro' },
			{ relativePath: 'api/01-courses.md', content: '# Courses' },
			{ relativePath: 'api/enroll.md', content: '---\nid: enrollments\n---\n# Enroll' },
		];
		const sidebar = "const sidebars = { docs: ['intro', { type: 'category', label: 'API', items: ['api/courses', 'api/enrollments'] }] };";
		expect(sidebarProblems(sidebar, docs)).toStrictEqual([]);
		expect(sidebarProblems("const s = { docs: ['intro', 'api/courses', 'api/gone'] };", docs)).toStrictEqual([
			'apps/docs/sidebars.ts lists "api/gone" but no page in apps/docs/docs/ has that id',
			'apps/docs/docs/api/enroll.md (id "api/enrollments") is missing from apps/docs/sidebars.ts',
		]);
		expect(sidebarProblems("const s = { docs: [{ type: 'autogenerated', dirName: '.' }] };", docs)).toStrictEqual([]);
	});
});
